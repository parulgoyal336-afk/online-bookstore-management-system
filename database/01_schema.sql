BEGIN FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN
 ('AUDIT_LOG','ORDER_ITEMS','ORDERS','CART','BOOKS','USERS')) LOOP
 EXECUTE IMMEDIATE 'DROP TABLE '||t.table_name||' CASCADE CONSTRAINTS'; END LOOP; END;
/
CREATE TABLE users (
 user_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 name VARCHAR2(100) NOT NULL, email VARCHAR2(120) NOT NULL UNIQUE,
 address VARCHAR2(250), password_hash VARCHAR2(64) NOT NULL,
 role VARCHAR2(10) DEFAULT 'USER' CHECK (role IN ('USER','ADMIN')),
 created_at DATE DEFAULT SYSDATE);
CREATE TABLE books (
 book_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 title VARCHAR2(200) NOT NULL, author VARCHAR2(120) NOT NULL, category VARCHAR2(60),
 price NUMBER(8,2) NOT NULL CHECK (price > 0),
 quantity NUMBER DEFAULT 0 NOT NULL CHECK (quantity >= 0));
CREATE TABLE cart (
 cart_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id NUMBER NOT NULL REFERENCES users ON DELETE CASCADE,
 book_id NUMBER NOT NULL REFERENCES books ON DELETE CASCADE,
 quantity NUMBER NOT NULL CHECK (quantity > 0), UNIQUE (user_id, book_id));
CREATE TABLE orders (
 order_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id NUMBER NOT NULL REFERENCES users, order_date DATE DEFAULT SYSDATE,
 total_amount NUMBER(10,2) DEFAULT 0,
 status VARCHAR2(12) DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSING','SHIPPED','DELIVERED','CANCELLED')));
CREATE TABLE order_items (
 item_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 order_id NUMBER NOT NULL REFERENCES orders ON DELETE CASCADE,
 book_id NUMBER NOT NULL REFERENCES books, quantity NUMBER NOT NULL, price NUMBER(8,2) NOT NULL);
CREATE TABLE audit_log (
 log_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 action VARCHAR2(30), details VARCHAR2(400), log_time TIMESTAMP DEFAULT SYSTIMESTAMP);
CREATE INDEX idx_books_title ON books(title);
CREATE INDEX idx_orders_user ON orders(user_id);
